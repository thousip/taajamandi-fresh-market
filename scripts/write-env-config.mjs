#!/usr/bin/env node
// Build-time environment selection for the static storefront (index.html) and staff app (staff.html).
//
// Writes public/env-config.js, which sets window.TAAJA_ENV before the page scripts run.
//   VERCEL_ENV=production          -> production Supabase (must be configured, must be the production project)
//   VERCEL_ENV=preview|development -> QA Supabase (production project is refused; build fails)
//   anything else / unset (local)  -> QA Supabase
// Only publishable (browser-safe) keys are accepted; secret/service-role keys fail the build.
//
// Usage: node scripts/write-env-config.mjs [--out <file>]   (default: public/env-config.js)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const PRODUCTION_REF = "qebdpjzhbqzjbvjqeztl";
export const QA_REF = "tcdpbutitfrtunarhxhz";
export const QA_DEFAULT = Object.freeze({
  url: `https://${QA_REF}.supabase.co`,
  publishableKey: "sb_publishable_A7Txz9NMqU_R1GIbUOgB-A_eevVdvpq",
});
// QA has no copies of the product photos; it reads them (read-only, public files) from production storage.
export const PRODUCTION_IMAGE_BASE = `https://${PRODUCTION_REF}.supabase.co/storage/v1/object/public/product-images/`;
// Hostnames that may run a production build. Any other host refuses to start (see index.html/staff.html).
export const PRODUCTION_HOSTS = Object.freeze([
  "taajamandi.vercel.app",
  "taajamandi-toxic-6dab.vercel.app",
  "taajamandi-git-main-toxic-6dab.vercel.app",
  "tajjamandi.in",
  "www.tajjamandi.in",
]);

export function projectRefFromUrl(url) {
  const m = /^https:\/\/([a-z0-9]{20})\.supabase\.co\/?$/.exec(String(url || "").trim());
  return m ? m[1] : null;
}

function assertPublishableKey(key) {
  const k = String(key || "");
  if (k.startsWith("sb_secret_")) throw new Error("A secret key was supplied; only publishable keys may reach the browser.");
  if (k.split(".").length === 3) {
    let payload = {};
    try { payload = JSON.parse(Buffer.from(k.split(".")[1], "base64url").toString("utf8")); } catch { /* not a JWT */ }
    if (payload.role && payload.role !== "anon") throw new Error(`A ${payload.role} key was supplied; only publishable keys may reach the browser.`);
  }
  if (!k) throw new Error("Missing publishable key.");
}

export function resolveEnvConfig(env) {
  const vercelEnv = env.VERCEL_ENV || "";
  const url = env.VITE_SUPABASE_URL || "";
  const key = env.VITE_SUPABASE_PUBLISHABLE_KEY || "";
  const ref = url ? projectRefFromUrl(url) : null;
  if (url && !ref) throw new Error(`VITE_SUPABASE_URL is not a Supabase project URL: ${url}`);

  if (vercelEnv === "production") {
    if (!url || !key) throw new Error("Production build needs VITE_SUPABASE_URL and VITE_SUPABASE_PUBLISHABLE_KEY.");
    if (ref !== PRODUCTION_REF) throw new Error(`Production build must use project ${PRODUCTION_REF}, got ${ref}.`);
    assertPublishableKey(key);
    return { environment: "production", projectRef: ref, supabaseUrl: url.replace(/\/$/, ""), publishableKey: key,
      imagePublicBase: null, allowedHosts: [...PRODUCTION_HOSTS], vercelEnv };
  }

  // preview, development, local or unknown: QA only
  if (ref === PRODUCTION_REF) throw new Error(`Non-production build (VERCEL_ENV=${vercelEnv || "unset"}) is configured with the production project; refusing.`);
  if (ref && ref !== QA_REF) throw new Error(`Non-production build must use the QA project ${QA_REF}, got ${ref}.`);
  const qaUrl = ref ? url.replace(/\/$/, "") : QA_DEFAULT.url;
  const qaKey = ref ? key : QA_DEFAULT.publishableKey;
  assertPublishableKey(qaKey);
  return { environment: "qa", projectRef: QA_REF, supabaseUrl: qaUrl, publishableKey: qaKey,
    imagePublicBase: PRODUCTION_IMAGE_BASE, allowedHosts: null, vercelEnv };
}

export function renderEnvConfig(cfg, commit = "") {
  const body = { ...cfg, commit: String(commit || "").slice(0, 7), builtAt: new Date().toISOString() };
  return `// Generated by scripts/write-env-config.mjs at build time. Do not edit or commit.\n` +
    `window.TAAJA_ENV = Object.freeze(${JSON.stringify(body, null, 2)});\n`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const outIdx = process.argv.indexOf("--out");
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const out = outIdx > -1 ? process.argv[outIdx + 1] : path.join(root, "public", "env-config.js");
  try {
    const cfg = resolveEnvConfig(process.env);
    fs.writeFileSync(out, renderEnvConfig(cfg, process.env.VERCEL_GIT_COMMIT_SHA));
    console.log(`[env-config] ${cfg.environment} -> ${cfg.projectRef} (VERCEL_ENV=${cfg.vercelEnv || "unset"}) written to ${path.relative(root, out) || out}`);
  } catch (e) {
    console.error(`[env-config] BUILD STOPPED: ${e.message}`);
    process.exit(1);
  }
}
